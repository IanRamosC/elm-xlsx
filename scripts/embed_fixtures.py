"""Embed the .xlsx fixtures in tests/Fixtures.elm as base64 strings, so
elm-test can read them.

Usage (from the repo root):
    python3 scripts/embed_fixtures.py
"""

import base64
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DIRS = ["tests/fixtures/edge", "tests/fixtures/xlsxwriter"]


def elm_name(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    parts = re.split(r"[^A-Za-z0-9]+", stem)
    return parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def main():
    entries = []
    for d in DIRS:
        for f in sorted(os.listdir(os.path.join(ROOT, d))):
            if f.endswith(".xlsx"):
                with open(os.path.join(ROOT, d, f), "rb") as fh:
                    entries.append((elm_name(f), f"{d}/{f}", base64.b64encode(fh.read()).decode()))
    names = ", ".join(n for n, _, _ in entries)
    out = [
        f"module Fixtures exposing ({names})",
        "",
        "{-| Generated by scripts/embed_fixtures.py. Do not edit. -}",
        "",
        "",
    ]
    for name, path, b64 in entries:
        out += [f"{{-| {path} -}}", f"{name} : String", f"{name} =", f'    "{b64}"', "", ""]
    with open(os.path.join(ROOT, "tests", "Fixtures.elm"), "w") as fh:
        fh.write("\n".join(out).rstrip() + "\n")
    print(f"embedded {len(entries)} fixtures")


if __name__ == "__main__":
    main()
